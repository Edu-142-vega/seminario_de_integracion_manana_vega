# Operadores Matematicos - Conteo de Evidencias y Armas Decomisadas
armas_decomisadas = 15
vehiculos_incautados = 20
print("Suma de Incautaciones")
print(armas_decomisadas, "+", vehiculos_incautados, "=", armas_decomisadas + vehiculos_incautados)
print("Diferencia")
print(armas_decomisadas, "-", vehiculos_incautados, "=", armas_decomisadas - vehiculos_incautados)
print("Multiplicacion de Folios")
print(armas_decomisadas, "*", vehiculos_incautados, "=", armas_decomisadas * vehiculos_incautados)
print("Promedio por Fiscalia")
print(armas_decomisadas, "/", vehiculos_incautados, "=", armas_decomisadas / vehiculos_incautados)
print("Potencia de Codigo de Seguridad")
print(armas_decomisadas, "**", vehiculos_incautados, "=", armas_decomisadas ** vehiculos_incautados)
print("División de Agentes por Cuadrante")
print(armas_decomisadas, "//", vehiculos_incautados, "=", armas_decomisadas // vehiculos_incautados)
print("Modulo de Turnos")
print(armas_decomisadas, "%", vehiculos_incautados, "=", armas_decomisadas % vehiculos_incautados)



import math
print(math.sqrt(15))  # Calculo de radio de patrullaje policial
print(math.ceil(3.2))  # Redondea hacia arriba asignacion de patrullas
print(math.floor(3.2))  # Redondea hacia abajo estimacion de horas de operativo
print(round(3.555552, 2))  # Redondea a 2 decimales el indice de prioridad del caso